class UploadValidationError(Exception):
    def __init__(self, message: str, status_code: int = 400):
        super().__init__(message)
        self.status_code = status_code


class DatabaseNotReadyError(RuntimeError):
    pass


def get_db_connection():
    """Open a short-lived PostgreSQL connection to Neon."""
    if not DATABASE_URL:
        raise DatabaseNotReadyError(
            "DATABASE_URL belum diatur. Isi connection string Neon di file .env."
        )

    try:
        import psycopg
        from psycopg.rows import dict_row
    except ImportError as exc:
        raise DatabaseNotReadyError(
            "Library psycopg belum terpasang. Jalankan pip install -r requirements.txt."
        ) from exc

    try:
        return psycopg.connect(
            DATABASE_URL,
            connect_timeout=10,
            sslmode="require",
            row_factory=dict_row,
        )
    except Exception as exc:
        app.logger.exception("Tidak dapat terhubung ke Neon PostgreSQL")
        raise DatabaseNotReadyError(
            "Tidak dapat terhubung ke database. Periksa DATABASE_URL dan koneksi Neon."
        ) from exc


def ensure_history_table(cursor) -> None:
    """Create the history table and index if they do not exist yet."""
    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS detection_history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            visitor_id VARCHAR(64) NOT NULL,
            original_filename TEXT NOT NULL,
            predicted_label VARCHAR(32) NOT NULL,
            confidence DOUBLE PRECISION NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """
    )
    cursor.execute(
        """
        CREATE INDEX IF NOT EXISTS idx_history_visitor_created
        ON detection_history (visitor_id, created_at DESC)
        """
    )


def read_and_validate_upload(uploaded_file):
    """Read and validate upload bytes once; shared by validation and prediction."""
    if uploaded_file is None or uploaded_file.filename == "":
        raise UploadValidationError("Pilih gambar terlebih dahulu.")

    original_name = Path(uploaded_file.filename).name
    extension = Path(original_name).suffix.lower()
    if extension not in ALLOWED_EXTENSIONS:
        raise UploadValidationError(
            "Format file belum didukung. Gunakan JPG, JPEG, PNG, atau WEBP."
        )

    file_bytes = uploaded_file.read()
    if not file_bytes:
        raise UploadValidationError("File yang dipilih kosong.")
    if len(file_bytes) > MAX_UPLOAD_BYTES:
        raise UploadValidationError("Ukuran gambar maksimal 4 MB.", 413)

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(BytesIO(file_bytes)) as image:
                image_format = image.format
                width, height = image.size
                image.verify()

        if image_format not in ALLOWED_FORMATS:
            raise UploadValidationError(
                "Isi file bukan gambar JPG, PNG, atau WEBP yang didukung."
            )
        if width <= 0 or height <= 0 or width * height > MAX_IMAGE_PIXELS:
            raise UploadValidationError("Resolusi gambar tidak valid atau terlalu besar.")

    except UploadValidationError:
        raise
    except (
        UnidentifiedImageError,
        OSError,
        Image.DecompressionBombError,
        Image.DecompressionBombWarning,
    ) as exc:
        raise UploadValidationError("Gambar tidak dapat dibaca atau file rusak.") from exc

    metadata = {
        "filename": original_name,
        "format": image_format,
        "width": width,
        "height": height,
        "size_kb": round(len(file_bytes) / 1024, 1),
    }
    return file_bytes, metadata


@app.before_request
def ensure_anonymous_visitor():
    """Give each browser a persistent anonymous visitor ID in a signed session."""
    if "visitor_id" not in session:
        session["visitor_id"] = uuid.uuid4().hex
    session.permanent = True


@app.get("/")
def home():
    return render_template("index.html")


@app.post("/validate-image")
def validate_image():
    """Validate image file only; does not run the ML model."""
    try:
        _file_bytes, metadata = read_and_validate_upload(request.files.get("image"))
    except UploadValidationError as exc:
        return jsonify({"ok": False, "message": str(exc)}), exc.status_code

    return jsonify({
        "ok": True,
        **metadata,
        "message": "Gambar valid dan siap diprediksi jika model sudah tersedia.",
    })


@app.post("/predict-image")
def predict_uploaded_image():
    """Validate an image, predict it, then save metadata to the visitor's history."""
    try:
        file_bytes, metadata = read_and_validate_upload(request.files.get("image"))
    except UploadValidationError as exc:
        return jsonify({"ok": False, "message": str(exc)}), exc.status_code

    try:
        with Image.open(BytesIO(file_bytes)) as source_image:
            image = source_image.convert("RGB")

        prediction = predict_image(image)
    except ModelNotReadyError as exc:
        return jsonify({"ok": False, "model_ready": False, "message": str(exc)}), 503
    except Exception:
        app.logger.exception("Gagal menjalankan prediksi gambar")
        return jsonify({
            "ok": False,
            "message": "Prediksi gagal karena terjadi kesalahan pada model. Periksa log server.",
        }), 500

    # Prediksi tetap dikembalikan jika database sedang tidak tersedia.
    # Dalam kondisi itu, antarmuka memberi tahu bahwa riwayat belum tersimpan.
    history_saved = False
    try:
        with get_db_connection() as connection:
            with connection.cursor() as cursor:
                ensure_history_table(cursor)
                cursor.execute(
                    """
                    INSERT INTO detection_history
                        (visitor_id, original_filename, predicted_label, confidence)
                    VALUES (%s, %s, %s, %s)
                    """,
                    (
                        session["visitor_id"],
                        metadata["filename"],
                        prediction["predicted_label"],
                        float(prediction["confidence"]),
                    ),
                )
        history_saved = True
    except Exception:
        app.logger.exception("Prediksi berhasil, tetapi riwayat gagal disimpan")

    return jsonify({
        "ok": True,
        **metadata,
        **prediction,
        "history_saved": history_saved,
        "history_message": None if history_saved else "Prediksi berhasil, tetapi riwayat belum tersimpan.",
    })


@app.get("/api/history")
def get_history():
    """Return only history belonging to this anonymous browser session."""
    try:
        with get_db_connection() as connection:
            with connection.cursor() as cursor:
                ensure_history_table(cursor)
                cursor.execute(
                    """
                    SELECT id, original_filename, predicted_label, confidence, created_at
                    FROM detection_history
                    WHERE visitor_id = %s
                    ORDER BY created_at DESC
                    LIMIT 100
                    """,
                    (session["visitor_id"],),
                )
                rows = cursor.fetchall()

        items = [
            {
                "id": row["id"],
                "original_filename": row["original_filename"],
                "predicted_label": row["predicted_label"],
                "confidence": float(row["confidence"]),
                "created_at": row["created_at"].isoformat(),
            }
            for row in rows
        ]
        return jsonify({"ok": True, "items": items})
    except DatabaseNotReadyError as exc:
        return jsonify({"ok": False, "message": str(exc)}), 503
    except Exception:
        app.logger.exception("Gagal mengambil riwayat deteksi")
        return jsonify({"ok": False, "message": "Riwayat belum dapat dimuat. Periksa koneksi database."}), 500


@app.delete("/api/history/<int:history_id>")
def delete_history_item(history_id: int):
    """Delete one history row only when it belongs to this visitor."""
    try:
        with get_db_connection() as connection:
            with connection.cursor() as cursor:
                ensure_history_table(cursor)
                cursor.execute(
                    """
                    DELETE FROM detection_history
                    WHERE id = %s AND visitor_id = %s
                    """,
                    (history_id, session["visitor_id"]),
                )
                deleted = cursor.rowcount
        if deleted == 0:
            return jsonify({"ok": False, "message": "Riwayat tidak ditemukan."}), 404
        return jsonify({"ok": True, "message": "Riwayat berhasil dihapus."})
    except DatabaseNotReadyError as exc:
        return jsonify({"ok": False, "message": str(exc)}), 503
    except Exception:
        app.logger.exception("Gagal menghapus satu riwayat")
        return jsonify({"ok": False, "message": "Riwayat gagal dihapus."}), 500


@app.delete("/api/history")
def delete_all_history():
    """Delete all history rows belonging to the current anonymous visitor."""
    try:
        with get_db_connection() as connection:
            with connection.cursor() as cursor:
                ensure_history_table(cursor)
                cursor.execute(
                    "DELETE FROM detection_history WHERE visitor_id = %s",
                    (session["visitor_id"],),
                )
                deleted = cursor.rowcount
        return jsonify({"ok": True, "deleted_count": deleted})
    except DatabaseNotReadyError as exc:
        return jsonify({"ok": False, "message": str(exc)}), 503
    except Exception:
        app.logger.exception("Gagal menghapus seluruh riwayat")
        return jsonify({"ok": False, "message": "Seluruh riwayat gagal dihapus."}), 500


